// ChatMCP local setup 1.0.0. Run through the adjacent PowerShell installer.
// No credentials are sent to the Desktop Commander child or printed here.
import fs from 'node:fs/promises';
import { constants } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { isDeepStrictEqual } from 'node:util';

export const PINNED_VERSION = '0.2.52';
const PREFIX = '[MCP-LOCAL]';
const say = (message) => console.log(`${PREFIX} ${message}`);
const object = (value) => value !== null && typeof value === 'object' && !Array.isArray(value);

function fail(code) {
  const error = new Error(code);
  error.safeCode = code;
  throw error;
}

export function parseConfig(bytes) {
  const parsed = JSON.parse(bytes.toString('utf8').replace(/^\uFEFF/, ''));
  if (!object(parsed)) fail('CONFIG_MUST_BE_AN_OBJECT');
  return parsed;
}

export function mergeProxy(config, entry, managedLauncher) {
  if (!object(config.mcpServers)) fail('MCP_SERVERS_OBJECT_MISSING');
  const cloud = config.mcpServers['cloud-harness'];
  if (!object(cloud) || !/^http:\/\/127\.0\.0\.1:\d+\/mcp\/?$/.test(cloud.url ?? '')) {
    fail('EXISTING_LOCAL_CLOUD_HARNESS_ENTRY_MISSING');
  }
  const existing = config.mcpServers['desktop-commander'];
  if (existing !== undefined && (!object(existing) || !Array.isArray(existing.args) || existing.args[0] !== managedLauncher)) {
    fail('EXISTING_DESKTOP_COMMANDER_ENTRY_IS_NOT_MANAGED_BY_THIS_SETUP');
  }
  // Spread retains all unrelated server entries and root-level settings.
  return {
    ...config,
    mcpServers: { ...config.mcpServers, 'desktop-commander': entry },
  };
}

async function readOptional(file) {
  try { return await fs.readFile(file); }
  catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}

async function backup(file, originalBytes, label) {
  if (originalBytes === null) return null;
  const timestamp = new Date().toISOString().replace(/[-:.]/g, '');
  const target = `${file}.${label}-${timestamp}-${randomUUID().slice(0, 8)}.bak`;
  await fs.writeFile(target, originalBytes, { flag: 'wx', mode: 0o600 });
  return target;
}

export async function replaceIfUnchanged(file, originalBytes, newBytes) {
  const actual = await readOptional(file);
  if (!(originalBytes === null ? actual === null : actual?.equals(originalBytes))) {
    fail('CONFIG_CHANGED_DURING_SETUP_RERUN_AFTER_OTHER_EDITOR_FINISHES');
  }
  const temporary = `${file}.${randomUUID()}.tmp`;
  try {
    await fs.writeFile(temporary, newBytes, { flag: 'wx', mode: 0o600 });
    // Check once more just before commit. Backups retain the original bytes.
    const latest = await readOptional(file);
    if (!(originalBytes === null ? latest === null : latest?.equals(originalBytes))) {
      fail('CONFIG_CHANGED_DURING_SETUP_RERUN_AFTER_OTHER_EDITOR_FINISHES');
    }
    await fs.rename(temporary, file);
  } finally {
    await fs.unlink(temporary).catch((error) => { if (error.code !== 'ENOENT') throw error; });
  }
}

function launcherSource() {
  return `// Generated by ChatMCP local setup 1.0.0. Contains no credentials.\n` +
    `import fs from 'node:fs/promises';\n` +
    `import { pathToFileURL } from 'node:url';\n` +
    `const settings = JSON.parse(await fs.readFile(new URL('./local-settings.json', import.meta.url), 'utf8'));\n` +
    `process.chdir(settings.projectPath);\n` +
    `await import(pathToFileURL(settings.entrypoint).href);\n`;
}

export async function configure(projectInput, proxyInput, runtimeInput, hooks = {}) {
  const projectPath = await fs.realpath(projectInput);
  if (!(await fs.stat(projectPath)).isDirectory()) fail('PROJECT_FOLDER_MISSING');
  const configPath = path.resolve(proxyInput);
  const runtimeDirectory = path.resolve(runtimeInput);
  const packageRoot = path.join(runtimeDirectory, 'node_modules', '@wonderwhy-er', 'desktop-commander');
  const packagePath = path.join(packageRoot, 'package.json');
  const manifest = parseConfig(await fs.readFile(packagePath));
  if (manifest.name !== '@wonderwhy-er/desktop-commander' || manifest.version !== PINNED_VERSION || manifest.bin?.['desktop-commander'] !== 'dist/index.js') {
    fail('PINNED_PACKAGE_OR_ENTRYPOINT_MISMATCH');
  }
  const entrypoint = path.join(packageRoot, 'dist', 'index.js');
  await fs.access(entrypoint, constants.R_OK);
  const launcherPath = path.join(runtimeDirectory, 'start-local.mjs');
  const entry = { command: process.execPath, args: [launcherPath, '--no-onboarding'] };
  const proxyBefore = await fs.readFile(configPath);
  const proxy = parseConfig(proxyBefore);
  const merged = mergeProxy(proxy, entry, launcherPath);

  // This path is the upstream package's shared, user-level configuration.
  // Keep every unrelated setting. Never replace HOME or redirect USERPROFILE.
  const dcConfigPath = hooks.configPath ?? path.join(os.homedir(), '.claude-server-commander', 'config.json');
  const dcBefore = await readOptional(dcConfigPath);
  const dcOriginal = dcBefore === null ? null : parseConfig(dcBefore);
  const desiredDirectories = [projectPath];
  const scopeAlreadySet = isDeepStrictEqual(dcOriginal?.allowedDirectories, desiredDirectories);
  const proxyAlreadySet = isDeepStrictEqual(proxy, merged);

  // Back up before spawning: the server can migrate its configuration at init.
  const dcBackup = await backup(dcConfigPath, dcBefore, 'before-chatmcp');
  if (dcBackup) say(`Desktop Commander configuration backup: ${dcBackup}`);
  if (!scopeAlreadySet) say('Setting file access to the selected project folder.');

  await fs.writeFile(launcherPath, launcherSource(), 'utf8');
  await fs.writeFile(path.join(runtimeDirectory, 'local-settings.json'), JSON.stringify({
    projectPath, entrypoint, desktopCommanderVersion: PINNED_VERSION,
  }, null, 2) + '\n', 'utf8');

  const resolveDependency = createRequire(packagePath);
  const { Client } = hooks.Client ? hooks : await import(pathToFileURL(resolveDependency.resolve('@modelcontextprotocol/sdk/client/index.js')).href);
  const { StdioClientTransport } = hooks.StdioClientTransport ? hooks : await import(pathToFileURL(resolveDependency.resolve('@modelcontextprotocol/sdk/client/stdio.js')).href);
  const transport = new StdioClientTransport({
    command: process.execPath,
    args: [launcherPath, '--no-onboarding'],
    cwd: projectPath,
    stderr: 'pipe',
  });
  // Upstream get_config logs full configuration on stderr. Drain but do not echo.
  transport.stderr?.on('data', () => {});
  const client = new Client({ name: 'chatmcp-local-setup', version: '1.0.0' }, { capabilities: {} });
  let connected = false;
  let scopeMutationAttempted = false;
  let proxyCommitted = false;
  let activePhase = 'initializing Desktop Commander';
  const deadline = setTimeout(() => {
    say(`Timed out during ${activePhase}. Configuration contents were not printed.`);
    if (scopeMutationAttempted) say('The directory setting may already be updated; check the local backup before undoing it.');
    if (!proxyCommitted) say('The browser proxy configuration was not committed by this setup.');
    void transport.close().finally(() => process.exit(1));
  }, 90000);
  deadline.unref();

  try {
    say('Testing the local MCP connection (initial start can take a moment)...');
    await client.connect(transport);
    connected = true;
    const listed = await client.listTools();
    const names = new Set(listed.tools.map((tool) => tool.name));
    for (const tool of ['set_config_value', 'get_config', 'list_directory', 'read_file', 'edit_block', 'start_process']) {
      if (!names.has(tool)) fail('REQUIRED_DESKTOP_COMMANDER_TOOL_MISSING');
    }
    activePhase = 'setting the project directory';
    if (!scopeAlreadySet) {
      scopeMutationAttempted = true;
      const result = await client.callTool({ name: 'set_config_value', arguments: { key: 'allowedDirectories', value: desiredDirectories } });
      if (result.isError) fail('COULD_NOT_SET_ALLOWED_DIRECTORIES');
    }
    const configResult = await client.callTool({ name: 'get_config', arguments: {} });
    if (configResult.isError || !isDeepStrictEqual(configResult.structuredContent?.config?.allowedDirectories, desiredDirectories)) {
      fail('ALLOWED_DIRECTORIES_VERIFICATION_FAILED');
    }
    const persisted = parseConfig(await fs.readFile(dcConfigPath));
    if (!isDeepStrictEqual(persisted.allowedDirectories, desiredDirectories)) fail('DIRECTORY_SCOPE_NOT_SAVED');
    activePhase = 'reading the selected project directory';
    const listing = await client.callTool({ name: 'list_directory', arguments: { path: projectPath, depth: 1 } });
    if (listing.isError) fail('PROJECT_DIRECTORY_READ_FAILED');
    say('PASS: Desktop Commander connected; required file and terminal tools are available.');
    say('PASS: file directory scope saved and the project folder can be read.');

    activePhase = 'updating the existing proxy configuration';
    if (!proxyAlreadySet) {
      const proxyBackup = await backup(configPath, proxyBefore, 'before-local');
      say(`Browser proxy configuration backup: ${proxyBackup}`);
      await replaceIfUnchanged(configPath, proxyBefore, Buffer.from(JSON.stringify(merged, null, 2) + '\n'));
      proxyCommitted = true;
      say('PASS: desktop-commander added to the existing browser proxy configuration.');
    } else {
      proxyCommitted = true;
      say('PASS: the existing browser proxy entry is already correct.');
    }
  } catch (error) {
    say(`STOPPED during ${activePhase}. Code: ${error.safeCode ?? error.code ?? error.name ?? 'SETUP_FAILED'}`);
    if (scopeMutationAttempted && !proxyCommitted && connected) {
      // Restore only the changed key through the server; preserve other clients'
      // concurrent configuration changes. Keep an original byte-for-byte backup.
      if (dcOriginal && Object.prototype.hasOwnProperty.call(dcOriginal, 'allowedDirectories')) {
        try {
          const current = parseConfig(await fs.readFile(dcConfigPath));
          if (isDeepStrictEqual(current.allowedDirectories, desiredDirectories)) {
            const restored = await client.callTool({ name: 'set_config_value', arguments: { key: 'allowedDirectories', value: dcOriginal.allowedDirectories } });
            if (restored.isError) throw new Error('restore failed');
            say('The previous allowedDirectories setting was restored.');
          } else if (!isDeepStrictEqual(current.allowedDirectories, dcOriginal.allowedDirectories)) {
            say('The directory setting changed in another process; review its backup locally.');
          }
        } catch {
          say('Could not restore the directory setting automatically; its backup is available locally.');
        }
      } else {
        say('No previous directory setting was available to restore; review the local configuration.');
      }
    }
    if (!proxyCommitted) say('The browser proxy configuration was not changed.');
    throw error;
  } finally {
    clearTimeout(deadline);
    await client.close().catch(() => transport.close().catch(() => {}));
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const [projectPath, configPath, runtimeDirectory] = process.argv.slice(2);
  if (projectPath === '--check-node') {
    const [major, minor] = process.versions.node.split('.').map(Number);
    if (major < 22 || (major === 22 && minor < 12)) {
      say('Node.js 22.12 or newer is required.');
      process.exitCode = 1;
    } else {
      say(`Node.js ${process.versions.node}`);
    }
  } else if (!projectPath || !configPath || !runtimeDirectory) {
    say('Run SETUP-MCP-LOCAL.ps1 with configure-local.mjs beside it.');
    process.exitCode = 1;
  } else {
    configure(projectPath, configPath, runtimeDirectory).catch((error) => {
      say(`Setup failed. Code: ${error.safeCode ?? error.code ?? error.name ?? 'SETUP_FAILED'}`);
      process.exitCode = 1;
    });
  }
}
