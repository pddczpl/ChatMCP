// The words of a report, in English and in Vietnamese (docs/PROOF-RENDER.md). Every Vietnamese text is NFC. A text holds no markup and no
// text of a pack: what stands in a `{placeholder}` is a number (written in the language of the report) or a node, and a text of a pack is
// a `code` node, which a renderer shows as a text and never reads as markup. So no text of a pack can become a word of the report.
