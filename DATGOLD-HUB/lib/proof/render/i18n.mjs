// ---------------------------------------------------------------------------------------------------------------------------- nodes
/** Words of the report itself. */
export const text = (value) => ({ type: 'text', value });
/** A text of the pack (or of the caller), shown as it is. */
export const code = (value) => ({ type: 'code', value: String(value) });
/** A short text of the pack that is not broken over lines: a criterion's id, a time. */
export const word = (value) => ({ type: 'word', value: String(value) });
/** A tree id or a digest, shown by its first digits. */
export const id = (value) => ({ type: 'id', value: String(value) });
/** The chip of a criterion's status or a check's result. */
export const chip = (kind, value) => ({ type: 'chip', kind, value });

