import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {dockerSandboxArgs} from '../lib/studio-sandbox.mjs';
import {previewStatus,validatePreview} from '../lib/studio-preview.mjs';
import {CodeIntelligence,LspProcess} from '../lib/studio-intelligence.mjs';
import {StudioWorkspace} from '../lib/studio-workspace.mjs';
import {StudioTerminal} from '../lib/studio-terminal.mjs';
import {PermissionGate} from '../lib/permissions.mjs';
let n=0;const check=(x,m)=>{assert.ok(x,m);n++};
const temp=await fs.mkdtemp(path.join(os.tmpdir(),'chatmcp-v2.2-'));
const repo=path.join(temp,'repo');await fs.mkdir(repo);
await fs.writeFile(path.join(repo,'module.py'),'import os\n\nclass Worker:\n    def work(self):\n        return calculate(4)\n\ndef calculate(a):\n    return a*2\n');
await fs.writeFile(path.join(repo,'app.ts'),'export function render(){return 4}\n');
await fs.writeFile(path.join(repo,'.env'),'SECRET=shhh');
const manager={workspace:repo,secrets:[],log:()=>{}};
const workspace=new StudioWorkspace({manager,directory:path.join(temp,'studio')});
const index=new CodeIntelligence({workspace,directory:path.join(temp,'index')});
const gate=new PermissionGate({manager,workspace,directory:path.join(temp,'policy')});
const terminal=new StudioTerminal({workspace});
try{
  const args=dockerSandboxArgs({workspace:repo,command:'python -m pytest -q',name:'chatmcp-sbox-123e4567-e89b-42d3-a456-426614174000'});
  check(args.includes('--network')&&args.includes('none'),'Docker network disabled');
  check(args.includes('--read-only')&&args.includes('ALL')&&args.includes('no-new-privileges'),'capabilities removed');
  check(args.includes(`type=bind,src=${repo},dst=/workspace,readonly`),'host files read-only');
  check(args.includes('--pull')&&args.includes('never'),'offline image only');
  check(!args.includes('--privileged')&&!args.includes('/var/run/docker.sock'),'no privileged host socket');
  assert.throws(()=>dockerSandboxArgs({workspace:repo,command:'hi',image:'bad image',name:'chatmcp-sbox-123e4567-e89b-42d3-a456-426614174000'}));n++;
  assert.throws(()=>validatePreview({port:80}));n++;
  assert.throws(()=>validatePreview({port:5173,pathname:'//evil.com'}));n++;
  const valid=validatePreview({port:5173,pathname:'/ui'});check(valid.url==='http://127.0.0.1:5173/ui','preview local only');
  const unbound=await previewStatus({port:65534});check(!unbound.ready,'unbound port safely reported');
  const report=await index.index();check(report.fileCount===2&&report.symbolCount>=3,'AST + TS index');
  const defs=await index.definitions({symbol:'calculate'});check(defs.matches.some(x=>x.path==='module.py'&&x.precision==='ast'),'Python AST exact definition');
  const refs=await index.references({symbol:'calculate'});check(refs.matches.some(x=>x.path==='module.py'&&x.line===5),'Python AST name references');
  const idx2=await index.index();check(idx2.reused===2,'index incremental cache reused');
  await fs.writeFile(path.join(repo,'module.py'),(await fs.readFile(path.join(repo,'module.py'),'utf8'))+'\ndef new_function(): pass\n');
  const idx3=await index.index();check(idx3.reused===1,'index updated only dirty source');
  const symbols=await index.symbols({query:'new_function'});check(symbols.matches.length===1,'new symbol indexed');
  check(!JSON.stringify(index.cache).includes('SECRET=shhh'),'private env skipped');
  const lsp=new LspProcess({root:repo,exe:process.execPath,args:[path.resolve('tests/fixtures/fake-lsp.mjs')],onDiagnostics:()=>{}});
  await lsp.start();check(lsp.ready,'LSP stdio initialized');
  const location=await lsp.request('textDocument/definition',{textDocument:{uri:'file:///test.py'},position:{line:0,character:0}});
  check(Array.isArray(location)&&location[0].range.start.line===0,'LSP definition request response');
  lsp.close();
  await gate.load();gate.configure({executionPolicy:'sandbox-only'});
  check((await gate.authorize({name:'desktop-commander.start_process',args:{command:'echo unsafe'},taskId:'any'})).allowed===false,'strict policy blocks host process');
  check((await gate.authorize({name:'desktop-commander.list_directory',args:{path:repo},taskId:'any'})).allowed===false,'strict policy also blocks external read tools');
  check((await gate.authorize({name:'studio.tree',args:{directory:''},taskId:'any'})).allowed===true,'built-in studio read allowed');
  gate.configure({executionPolicy:'host-review'});check(gate.state().executionPolicy==='host-review','host review opt in');
  const t=await terminal.start({interactive:true,command:'echo SESSION_READY',timeoutMinutes:.2});
  check(t.interactive&&['conpty','pipes'].includes(t.mode),'interactive session started');
  // Poll with a generous bound instead of fixed sleeps: loaded CI runners can take well over a second to start a shell.
  const terminalLog=()=>terminal.state().find(x=>x.id===t.id).logs.map(x=>x.message).join('');
  const waitForLog=async(text,ms=15000)=>{const until=Date.now()+ms;while(!terminalLog().includes(text)&&Date.now()<until)await new Promise(r=>setTimeout(r,25));};
  await waitForLog('SESSION_READY');
  terminal.write(t.id,'echo AFTER_STDIN\n');
  await waitForLog('AFTER_STDIN');
  const log=terminalLog();
  check(log.includes('SESSION_READY')&&log.includes('AFTER_STDIN'),'persistent shell accepted stdin');
  terminal.stop(t.id);
  console.log(`PASS ${n} v2.2 core assertions: Docker sandbox contract, AST incremental index, LSP stdio, strict policy, interactive terminal, preview validation`);
}finally{index.close();gate.shutdown();await terminal.close();await fs.rm(temp,{recursive:true,force:true,maxRetries:20,retryDelay:200}).catch(()=>{});}
